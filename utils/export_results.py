import os
import re
import pandas as pd


def parse_result_file(
    input_path="result_long_term_forecast.txt",
    output_csv="docs/results/raw/results.csv",
):
    """
    Parses result_long_term_forecast.txt generated by TimeXer runs
    and exports structured results to a CSV file.
    """
    if not os.path.exists(input_path):
        print(f"File {input_path} does not exist.")
        return None

    with open(input_path, "r", encoding="utf-8") as f:
        content = f.read()

    # Pattern matches setting line and subsequent metric line:
    # setting line: task_modelid_model_data_ft...
    # metric line: mse:..., mae:...
    blocks = re.findall(
        r"([^\n]+?)\s*\n\s*mse:([0-9.]+),\s*mae:([0-9.]+)", content
    )

    records = []
    for setting, mse, mae in blocks:
        setting = setting.strip()
        record = {
            "setting": setting,
            "mse": float(mse),
            "mae": float(mae),
        }

        # Extract common fields from setting string if available
        # Format typically: task_modelid_model_data_ft...
        match_ft = re.search(r"_ft([A-Za-z]+)_", setting)
        if match_ft:
            record["features"] = match_ft.group(1)

        match_sl = re.search(r"_sl(\d+)_", setting)
        if match_sl:
            record["seq_len"] = int(match_sl.group(1))

        match_pl = re.search(r"_pl(\d+)_", setting)
        if match_pl:
            record["pred_len"] = int(match_pl.group(1))

        match_dm = re.search(r"_dm(\d+)_", setting)
        if match_dm:
            record["d_model"] = int(match_dm.group(1))

        match_seed = re.search(r"seed[_-]?(\d+)", setting, re.IGNORECASE)
        if match_seed:
            record["seed"] = int(match_seed.group(1))
        else:
            record["seed"] = None

        records.append(record)

    df = pd.DataFrame(records)
    os.makedirs(os.path.dirname(output_csv), exist_ok=True)
    df.to_csv(output_csv, index=False)
    print(f"Exported {len(df)} records to {output_csv}")
    return df


if __name__ == "__main__":
    parse_result_file()
